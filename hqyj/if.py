age = int(input("年龄："))

if age >= 100:
    print("棋艺")
elif age >= 80:
    print("耄耋")
elif age >= 70:
    print("古稀")
elif age >= 60:
    print("花甲")
elif age >= 50:
    print("天猫")
elif age >= 40:
    print("补货")
elif age >= 30:
    print("而立")
elif age >= 20:
    print("弱冠")
else:
    print("孩子")